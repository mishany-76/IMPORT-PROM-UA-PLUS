def classify_row(row):
    """
    Классифицирует одну строку товара на 3 уровня с учетом поставщика,
    логистики и строгого двуязычия (RU/UKR).
    """
    supp = str(row.get('Особисті_нотатки', '')).strip().upper()
    data_src = str(row.get('Джерело_даних', '')).lower()
    name_ru = str(row.get('Назва_позиції', ''))
    name_uk = str(row.get('Назва_позиції_укр', ''))
    old_grp = str(row.get('Назва_групи', ''))
    text = f"{name_ru} {name_uk} {old_grp}".lower()

    # 1. Поставщик AGER (доставка Новой Почтой и Укрпочтой)
    if supp == 'AGER' or 'ager' in data_src:
        # Проверяем специализированные правила AGER
        for l1_r, l1_u, l2_r, l2_u, l3_base_r, l3_base_u, pat in AGER_RULES:
            if re.search(pat, text):
                return {
                    'l1_ru': l1_r, 'l1_uk': l1_u,
                    'l2_ru': l2_r, 'l2_uk': l2_u,
                    'l3_ru': f"{l3_base_r} (НП / УП)",
                    'l3_uk': f"{l3_base_u} (НП / УП)"
                }

        # Fallback для AGER, если точный шаблон не совпал
        if any(k in text for k in ['чоловіч', 'мужск']):
            return {
                'l1_ru': "Обувь", 'l1_uk': "Взуття",
                'l2_ru': "Мужская обувь (НП / УП)", 'l2_uk': "Чоловіче взуття (НП / УП)",
                'l3_ru': "Мужские кроссовки (НП / УП)", 'l3_uk': "Чоловічі кросівки (НП / УП)"
            }
        else:
            return {
                'l1_ru': "Обувь", 'l1_uk': "Взуття",
                'l2_ru': "Женская обувь (НП / УП)", 'l2_uk': "Жіноче взуття (НП / УП)",
                'l3_ru': "Женские кроссовки (НП / УП)", 'l3_uk': "Жіночі кросівки (НП / УП)"
            }

    # 2. Все остальные поставщики (IZIDROP, MOYDROP, KIRS, BAGSROOM, FOOTBALLERS)
    # Отправка ТОЛЬКО Новой Почтой — без суффиксов в названии
    for l1_r, l1_u, l2_r, l2_u, pat in STANDARD_RULES:
        if re.search(pat, text):
            # Для стандартных поставщиков L3 совпадает с L2 (без лишних суффиксов)
            return {
                'l1_ru': l1_r, 'l1_uk': l1_u,
                'l2_ru': l2_r, 'l2_uk': l2_u,
                'l3_ru': l2_r, 'l3_uk': l2_u
            }

    # 3. Общий Fallback по поставщику
    if supp == 'BAGSROOM' or any(k in text for k in ['сумк', 'рюкзак', 'гаманець', 'кошелек', 'пояс', 'ремень']):
        return {
            'l1_ru': "Сумки, рюкзаки и аксессуары", 'l1_uk': "Сумки, рюкзаки та аксесуари",
            'l2_ru': "Сумки и клатчи", 'l2_uk': "Сумки та клатчі",
            'l3_ru': "Сумки и клатчи", 'l3_uk': "Сумки та клатчі"
        }
    elif supp == 'FOOTBALLERS':
        return {
            'l1_ru': "Футбольная экипировка", 'l1_uk': "Футбольне екіпірування",
            'l2_ru': "Футбольная обувь и бутсы", 'l2_uk': "Футбольне взуття та бутси",
            'l3_ru': "Футбольная обувь и бутсы", 'l3_uk': "Футбольне взуття та бутси"
        }
    else:
        # По умолчанию обувь
        return {
            'l1_ru': "Обувь", 'l1_uk': "Взуття",
            'l2_ru': "Кроссовки", 'l2_uk': "Кросівки",
            'l3_ru': "Кроссовки", 'l3_uk': "Кросівки"
        }


def normalize_catalog_structure(merged_products_df, groups_cols):
    """
    Нормализует привязку товаров и формирует чистое дерево групп.
    """
    logging.info(f"Начало нормализации каталога для {len(merged_products_df)} товаров...")

    classifications = []
    for _, row in merged_products_df.iterrows():
        classifications.append(classify_row(row))

    # Сбор уникальных групп для дерева
    # L1: ключ (l1_ru, l1_uk)
    # L2: ключ (l1_ru, l1_uk, l2_ru, l2_uk)
    # L3: ключ (l1_ru, l1_uk, l2_ru, l2_uk, l3_ru, l3_uk)

    l1_set = sorted(list(set((c['l1_ru'], c['l1_uk']) for c in classifications)))
    l1_ids = {}
    for idx, (l1_ru, l1_uk) in enumerate(l1_set, start=10001):
        l1_ids[(l1_ru, l1_uk)] = str(idx)

    l2_set = sorted(list(set((c['l1_ru'], c['l1_uk'], c['l2_ru'], c['l2_uk']) for c in classifications)))
    l2_ids = {}
    for idx, (l1_ru, l1_uk, l2_ru, l2_uk) in enumerate(l2_set, start=20001):
        l2_ids[(l1_ru, l1_uk, l2_ru, l2_uk)] = str(idx)

    # L3 создается только если L3 отличается от L2 (как у AGER с НП/УП),
    # иначе L2 является конечной группой (чтобы не плодить бессмысленные дубли-подуровни!)
    l3_records = []
    prod_target_ids = []
    prod_target_names = []

    for c in classifications:
        l1_k = (c['l1_ru'], c['l1_uk'])
        l2_k = (c['l1_ru'], c['l1_uk'], c['l2_ru'], c['l2_uk'])
        p_l2_id = l2_ids[l2_k]

        if c['l3_ru'] != c['l2_ru']:
            # Есть специфичный подуровень 3 (например, у AGER)
            l3_k = (c['l1_ru'], c['l1_uk'], c['l2_ru'], c['l2_uk'], c['l3_ru'], c['l3_uk'])
            l3_records.append(l3_k)
        else:
            # Конечной является L2
            pass

    unique_l3 = sorted(list(set(l3_records)))
    l3_ids = {}
    for idx, (l1_r, l1_u, l2_r, l2_u, l3_r, l3_u) in enumerate(unique_l3, start=30001):
        l3_ids[(l1_r, l1_u, l2_r, l2_u, l3_r, l3_u)] = str(idx)

    # Привязываем каждый товар к его реальной конечной группе
    for c in classifications:
        if c['l3_ru'] != c['l2_ru']:
            l3_k = (c['l1_ru'], c['l1_uk'], c['l2_ru'], c['l2_uk'], c['l3_ru'], c['l3_uk'])
            gid = l3_ids[l3_k]
            gname = c['l3_ru']
        else:
            l2_k = (c['l1_ru'], c['l1_uk'], c['l2_ru'], c['l2_uk'])
            gid = l2_ids[l2_k]
            gname = c['l2_ru']

        prod_target_ids.append(gid)
        prod_target_names.append(gname)

    merged_products_df['Номер_групи'] = prod_target_ids
    merged_products_df['Ідентифікатор_групи'] = prod_target_ids
    merged_products_df['Назва_групи'] = prod_target_names

    # Формируем строки для Export Groups Sheet
    groups_rows = []

    # Уровень 1 (Корневой: Обувь, Сумки, Футбол, Детская мебель)
    for (l1_ru, l1_uk), gid in l1_ids.items():
        row = {col: '' for col in groups_cols}
        row['Номер_групи'] = gid
        row['Ідентифікатор_групи'] = gid
        row['Назва_групи'] = l1_ru
        row['Назва_групи_укр'] = l1_uk
        row['Номер_батьківської_групи'] = ''
        row['Ідентифікатор_батьківської_групи'] = ''
        groups_rows.append(row)

    # Уровень 2
    for (l1_ru, l1_uk, l2_ru, l2_uk), gid in l2_ids.items():
        row = {col: '' for col in groups_cols}
        row['Номер_групи'] = gid
        row['Ідентифікатор_групи'] = gid
        row['Назва_групи'] = l2_ru
        row['Назва_групи_укр'] = l2_uk
        p_id = l1_ids[(l1_ru, l1_uk)]
        row['Номер_батьківської_групи'] = p_id
        row['Ідентифікатор_батьківської_групи'] = p_id
        groups_rows.append(row)

    # Уровень 3 (только реальные подуровни, напр. Мужские кроссовки (НП / УП))
    for (l1_r, l1_u, l2_r, l2_u, l3_r, l3_u), gid in l3_ids.items():
        row = {col: '' for col in groups_cols}
        row['Номер_групи'] = gid
        row['Ідентифікатор_групи'] = gid
        row['Назва_групи'] = l3_r
        row['Назва_групи_укр'] = l3_u
        p_id = l2_ids[(l1_r, l1_u, l2_r, l2_u)]
        row['Номер_батьківської_групи'] = p_id
        row['Ідентифікатор_батьківської_групи'] = p_id
        groups_rows.append(row)

    optimized_groups_df = pd.DataFrame(groups_rows, columns=groups_cols)
